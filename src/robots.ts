import { VERSION } from './generated/registry.js';
import { crawlers, getCrawler } from './registry.js';
import { CATEGORIES, type Category, type Crawler } from './types.js';

export type RobotsRule = 'allow' | 'disallow';

export interface RobotsTxtOptions {
  /** A rule per category, e.g. `{ 'ai-training': 'disallow' }`. Unlisted categories are left alone. */
  categories?: Partial<Record<Category, RobotsRule>>;
  /**
   * Per-crawler overrides keyed by id or token (`'gptbot'`, `'Google-Extended'`).
   * They win over category rules.
   */
  crawlers?: Record<string, RobotsRule>;
  /** Paths to disallow for blocked crawlers. Default `['/']`. */
  paths?: string[];
  /** Sitemap URLs to append. */
  sitemaps?: string[];
  /** Include explanatory comments. Default `true`. */
  comments?: boolean;
}

/**
 * Generates robots.txt groups that block crawlers by category or by name,
 * using each operator's documented robots.txt tokens.
 *
 * Only blocked crawlers get a group: a crawler named in its own group stops
 * reading your `User-agent: *` rules, so "allow" is expressed by leaving it
 * out. Append the output to your existing robots.txt.
 *
 * @example
 * robotsTxt({ categories: { 'ai-training': 'disallow' }, crawlers: { 'Applebot-Extended': 'allow' } })
 */
export function robotsTxt(options: RobotsTxtOptions = {}): string {
  const overrides = new Map<string, RobotsRule>();
  const unknown: string[] = [];
  for (const [key, rule] of Object.entries(options.crawlers ?? {})) {
    const crawler = getCrawler(key);
    if (crawler) overrides.set(crawler.id, rule);
    else unknown.push(key);
  }
  if (unknown.length > 0) {
    throw new Error(`robotsTxt: unknown crawler(s): ${unknown.join(', ')}. See \`crawlerid list\`.`);
  }
  for (const category of Object.keys(options.categories ?? {})) {
    if (!CATEGORIES.includes(category as Category)) {
      throw new Error(`robotsTxt: unknown category "${category}". Expected one of: ${CATEGORIES.join(', ')}.`);
    }
  }

  const blocked = (crawler: Crawler): boolean =>
    (overrides.get(crawler.id) ?? options.categories?.[crawler.category]) === 'disallow';

  const comments = options.comments ?? true;
  const paths = options.paths && options.paths.length > 0 ? options.paths : ['/'];
  const lines: string[] = [];
  if (comments) {
    lines.push(`# Generated by crawlerid ${VERSION} - https://github.com/crawlerid/crawlerid`);
  }

  for (const category of CATEGORIES) {
    const group = crawlers.filter((c) => c.category === category && c.robotsTokens.length > 0 && blocked(c));
    if (group.length === 0) continue;
    if (lines.length > 0) lines.push('');
    if (comments) {
      lines.push(`# ${category}: ${[...new Set(group.map((c) => c.operator))].join(', ')}`);
      if (group.some((c) => c.respectsRobotsTxt === false)) {
        lines.push('# Some of these fetch on behalf of a user and may ignore robots.txt; enforce with verify().');
      }
    }
    for (const token of new Set(group.flatMap((c) => c.robotsTokens))) lines.push(`User-agent: ${token}`);
    for (const path of paths) lines.push(`Disallow: ${path}`);
  }

  if (options.sitemaps && options.sitemaps.length > 0) {
    lines.push('');
    for (const sitemap of options.sitemaps) lines.push(`Sitemap: ${sitemap}`);
  }
  return `${lines.join('\n')}\n`;
}
